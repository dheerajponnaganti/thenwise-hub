// Generates src/api/types.ts from api/openapi.json (a copy of thenwise's frozen spec).
// `--check` fails when the committed types do not match the spec, and names the first difference.
import { readFileSync, writeFileSync } from 'node:fs'
import openapiTS, { astToString } from 'openapi-typescript'

const spec = process.env.HUB_SPEC ?? 'api/openapi.json'
const out = process.env.HUB_TYPES ?? 'src/api/types.ts'
const fresh = '// Generated by scripts/gen-types.mjs from api/openapi.json. Do not edit.\n' + astToString(await openapiTS(new URL(spec, `file://${process.cwd()}/`)))

if (process.argv.includes('--check')) {
  const have = readFileSync(out, 'utf8').split('\n')
  const want = fresh.split('\n')
  const i = want.findIndex((l, n) => l !== have[n])
  if (i >= 0 || have.length !== want.length) {
    console.error(`API types are out of date with ${spec} (first difference at line ${i + 1}: expected "${want[i] ?? ''}", found "${have[i] ?? ''}"). Run npm run gen:types.`)
    process.exit(1)
  }
} else writeFileSync(out, fresh)
